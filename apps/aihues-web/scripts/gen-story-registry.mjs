import { readdirSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

/* Regenerates app/components/story-scenes/registry.ts from the per-article scene
   files in that directory. Each <slug>.tsx default-exports a scene component;
   this maps slug -> component. Run after adding/removing a scene file:
     node scripts/gen-story-registry.mjs
   Never hand-edit registry.ts. */

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'app', 'components', 'story-scenes');

const slugs = readdirSync(dir)
  .filter((f) => f.endsWith('.tsx') && f !== '_kit.tsx')
  .map((f) => f.replace(/\.tsx$/, ''))
  .sort();

const imports = slugs.map((s, i) => `import s${i} from './${s}';`).join('\n');
const entries = slugs.map((s, i) => `  '${s}': s${i},`).join('\n');

const out = `import type { ComponentType } from 'react';

// GENERATED by scripts/gen-story-registry.mjs — do not edit by hand.
${imports}

export const GENERATED_SCENES: Record<string, ComponentType> = {
${entries}
};
`;

writeFileSync(join(dir, 'registry.ts'), out);
console.log(`story registry: ${slugs.length} scene(s)`);
